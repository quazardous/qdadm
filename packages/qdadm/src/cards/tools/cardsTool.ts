/**
 * The cards' tooling (#5339), for qdadm's cards and an app's own: read the
 * card folders, write the index and the bestiary, and check them.
 *
 * A card is a folder: `meta.json` (its sheet), `schema.json` (the JSON
 * Schema of its data) and its body (a .vue file).
 *
 *   import { writeCardsIndex, checkCards } from '@quazardous/qdadm/cards/tools'
 *   writeCardsIndex('src/cards', { index: 'src/cards/cards-index.json', bestiary: 'docs/cards.md' })
 *   expect(checkCards('src/cards', { index: …, bestiary: … })).toEqual([])
 *
 * Node only: it reads and writes files.
 */
import fs from 'node:fs'
import path from 'node:path'
import { validateCardData, type CardSchema } from '../validate.js'

export interface CardFolder {
  /** The folder's name, which is the card's type */
  type: string
  dir: string
  meta: Record<string, unknown> | null
  schema: CardSchema | null
  /** The body's file name, or null */
  component: string | null
}

export interface CardsOutputs {
  /** Where the index (JSON) is written */
  index?: string
  /** Where the bestiary (Markdown) is written */
  bestiary?: string
  /** The bestiary's first heading (default "Cards") */
  title?: string
}

const SHEET_FIELDS = ['type', 'title', 'question', 'readings', 'strengths', 'avoid', 'sizes', 'options', 'action', 'example'] as const

function readJson(file: string): Record<string, unknown> | null {
  if (!fs.existsSync(file)) return null
  return JSON.parse(fs.readFileSync(file, 'utf8')) as Record<string, unknown>
}

/** The card folders under `dir`, sorted by type */
export function readCards(dir: string): CardFolder[] {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => {
      const folder = path.join(dir, e.name)
      const files = fs.readdirSync(folder)
      return {
        type: e.name,
        dir: folder,
        meta: readJson(path.join(folder, 'meta.json')),
        schema: readJson(path.join(folder, 'schema.json')) as CardSchema | null,
        component: files.find((f) => f.endsWith('.vue')) ?? null,
      }
    })
    .filter((c) => c.meta || c.schema || c.component)
    .sort((a, b) => a.type.localeCompare(b.type))
}

/** The index: every card's sheet and schema, for agents and tools */
export function buildIndex(cards: CardFolder[]): string {
  const index = {
    generatedBy: 'qdadm-cards index',
    cards: cards.filter((c) => c.meta).map((c) => ({ ...c.meta, schema: c.schema })),
  }
  return JSON.stringify(index, null, 2) + '\n'
}

const list = (items: unknown) => (Array.isArray(items) ? items.map((i) => `- ${String(i)}`).join('\n') : '')

/** The bestiary: the same sheets, written for a reader choosing a card */
export function renderBestiary(cards: CardFolder[], title = 'Cards'): string {
  const out: string[] = [
    '<!-- Generated by `qdadm-cards index` from each card\'s meta.json and schema.json: do not edit by hand. -->',
    '',
    `# ${title}`,
    '',
    'Each card answers one question. Pick the card by its question, then give it data of the shape its schema says: the card draws it, the envelope is the same for all.',
    '',
    '## The envelope',
    '',
    '| Field | What it says |',
    '|---|---|',
    '| `title` | What the card counts |',
    '| `icon` | An icon class before the title; default the type\'s own (below), `null` for none |',
    '| `status` | `critical`, `watch`, `good` or `info`: a side bar, a hue and a word |',
    '| `source`, `freshness` | Where the data comes from, and when it was read |',
    '| `to` | The surface: the whole card opens the domain\'s board |',
    '| `action` | `{ verb, count, mode, to \\| run \\| onClick }`: the one gesture. `mode: next` opens the most urgent item, `list` the filtered list; `run` walks the items behind the card with the run bar |',
    '| `links` | `[{ label, icon, to \\| run \\| onClick }]`: secondary gestures in the foot, beside the action (\"See all\"); the foot\'s CTA zone holds them, the action and the app\'s own buttons (`#cta` slot); a dashboard block adds its own with `card.links` |',
    '| `state` | `ready`, or `loading`, `unreachable` (with `error`), `empty` (with `emptyText`): drawn instead of the body |',
    '| `size` | `s`, `m` or `l`: 1, 2 or 3 columns, among the card\'s sizes |',
    '| `blocks` | Blocks drawn under the type\'s own body (below): a 7-day curve under a metric, a note. A dashboard block adds its own with `card.blocks` |',
    '',
    'Data that does not fit the schema draws the `invalid` state with the path and the reason; the rest of the board keeps working.',
    '',
    '## Blocks',
    '',
    'A card is a few blocks in order, its foot the CTA zone; a `flash` banner goes to its place in the card. The types below are ready-made assemblies of them (`metric` is value + viz + list). Compose your own three ways: the `blocks` type (`data: { blocks: [...] }`), `envelope.blocks` under any type\'s body, or a type declared by blocks: `registerCard({ type, meta, schema, blocks: (data, options, size) => [...] })`, with no component. Each block is checked against its kind; one that does not fit says which field.',
    '',
    '| Kind | Fields | Draws |',
    '|---|---|---|',
    '| `value` | `value`, `unit`, `decimals`, `label`, `badge`, `delta: { value, period }`, `higherIs`; or `then: { value, label }` with `changeAs` (`points`, `percent`) | The number, what it counts, its change toned by `higherIs`; with `then`, now and then side by side and the change |',
    '| `viz` | `series`: numbers, or `[{ label, points, tone }]` with points as `[time, value]`, `{ t, v, low, high }` or numbers; `chart` (`line`, `area`, `bars`, `stacked`, or a chart the app registered with `registerChart`); `stacked` (areas or bars); `period` (`24h`, `7d`, `30d`); `warning`, `critical`; `normal: { low, high }`; `unit`, `decimals`; `compact`; `dot`; `label` | A small chart, Munin-like: the thresholds as dashed lines, the band of normal and the points outside it. At size `s` (or `compact`) a sparkline; larger, the time axis, the y range, a legend for several series, and a tooltip per column on hover or with the arrow keys |',
    '| `list` | `items: [{ label, to, tag, tagStatus, at, status, value, age, due, action }]`, `look` (`hot`, `queue`, `feed`, `ranking`), `max`, `more`, `now`, `ageUnit`, `unit`, `bars` | Lines, each opening its item: hot lines with a tag; a queue warming with age; a feed, latest first; a ranking with bars |',
    '| `text` | `text`, `tone`, `strong`, `look` (`note`, `reading`) | A short text in its tone, a word in bold after it |',
    '| `progress` | `value`, `target`, `look` (`goal`, `bullet`); goal: `start`, `due`, `now`; bullet: `thresholds`, `min`, `max`, `higherIs`; `unit`, `decimals` | A goal\'s bar and pace, or a bullet graph with its ranges |',
    '| `parts` | `parts: [{ label, value, to }]`, `max`, `unit` | A whole in parts: one split bar and its legend, past `max` in "others" |',
    '| `flash` | `messages: [{ level, text, to }]` (or one `level`, `text`, `to`), `level` (`info`, `warning`, `critical`), `place` (`top`, `bottom`), `dismissible`, `id` | A "flash info" banner, an urgent word about the card: under the header (`top`) or above the foot (`bottom`), wherever it is declared, and shown whatever the card\'s state. The most serious first; a critical one is an alert. Dismissible: gone until the card is drawn again, for the session with an `id` |',
    '',
  ]
  for (const c of cards) {
    const m = c.meta
    if (!m) continue
    const options = (m.options ?? {}) as Record<string, Record<string, unknown>>
    const example = m.example as Record<string, unknown> | undefined
    const required = (c.schema?.required ?? []).map((r) => `\`${r}\``).join(', ')
    out.push(
      `## \`${c.type}\`: ${String(m.question)}`,
      '',
      `**Readings**`,
      '',
      list(m.readings),
      '',
      `**Strengths**`,
      '',
      list(m.strengths),
      '',
      `**Avoid it**`,
      '',
      list(m.avoid),
      '',
      `**Sizes**: ${(m.sizes as string[] | undefined)?.join(', ') ?? 's'}.${m.icon ? ` **Icon**: \`${String(m.icon)}\`.` : ''} **Main action**: ${String(m.action)}`,
      ''
    )
    if (Object.keys(options).length) {
      out.push('| Option | Type | Default | What it does |', '|---|---|---|---|')
      for (const [name, o] of Object.entries(options)) {
        const type = Array.isArray(o.enum) ? (o.enum as unknown[]).map((v) => `\`${String(v)}\``).join(' \\| ') : String(o.type ?? '')
        out.push(`| \`${name}\` | ${type} | ${o.default === undefined ? '' : `\`${JSON.stringify(o.default)}\``} | ${String(o.description ?? '')} |`)
      }
      out.push('')
    }
    out.push(`**Data**: required ${required || 'nothing'}; the full shape is in \`${c.type}/schema.json\`.`, '')
    if (example) {
      out.push('**Example**', '', '```json', JSON.stringify({ type: c.type, data: example.data, options: example.options ?? {} }, null, 2), '```', '')
    }
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n')
}

/** Write the index and the bestiary from the card folders */
export function writeCardsIndex(dir: string, outputs: CardsOutputs): void {
  const cards = readCards(dir)
  if (outputs.index) fs.writeFileSync(outputs.index, buildIndex(cards))
  if (outputs.bestiary) fs.writeFileSync(outputs.bestiary, renderBestiary(cards, outputs.title))
}

/**
 * What is wrong with the card folders, as sentences; empty when all is well.
 * A card without a sheet or a schema, a sheet missing a field, an example
 * that fails its own schema, an index or a bestiary out of date.
 */
export function checkCards(dir: string, outputs: CardsOutputs = {}): string[] {
  const problems: string[] = []
  const cards = readCards(dir)
  for (const c of cards) {
    if (!c.meta) {
      problems.push(`${c.type}: no meta.json (the card's sheet)`)
      continue
    }
    if (!c.schema) problems.push(`${c.type}: no schema.json`)
    if (!c.component) problems.push(`${c.type}: no .vue body`)
    for (const field of SHEET_FIELDS) {
      if (c.meta[field] === undefined) problems.push(`${c.type}: the sheet has no "${field}"`)
    }
    if (c.meta.type !== undefined && c.meta.type !== c.type) problems.push(`${c.type}: the sheet says type "${String(c.meta.type)}"`)
    const example = c.meta.example as { data?: unknown; options?: Record<string, unknown> } | undefined
    if (example && c.schema) {
      for (const p of validateCardData(example.data, c.schema, 'example.data')) problems.push(`${c.type}: ${p.path} ${p.message}`)
    }
    if (example?.options) {
      const optionsSchema: CardSchema = { type: 'object', properties: (c.meta.options ?? {}) as Record<string, CardSchema>, additionalProperties: false }
      for (const p of validateCardData(example.options, optionsSchema, 'example.options')) problems.push(`${c.type}: ${p.path} ${p.message}`)
    }
  }
  const stale = (file: string, expected: string, what: string) => {
    if (!fs.existsSync(file)) problems.push(`${what} ${file} is missing: run qdadm-cards index`)
    else if (fs.readFileSync(file, 'utf8') !== expected) problems.push(`${what} ${file} is out of date: run qdadm-cards index`)
  }
  if (outputs.index) stale(outputs.index, buildIndex(cards), 'the index')
  if (outputs.bestiary) stale(outputs.bestiary, renderBestiary(cards, outputs.title), 'the bestiary')
  return problems
}
